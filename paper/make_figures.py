"""Regenerate every paper table and figure from committed result files. One command:

    python paper/make_figures.py            # add PYTHONPATH=src if grnbench is not installed

Rules: outputs in paper/tables and paper/figures are never edited by hand; each entry below reads
only files under benchmarks/results/ and names the experiment it comes from. To add a table or
figure, add a function and register it in OUTPUTS.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src"), str(ROOT / "benchmarks")]
RESULTS = ROOT / "benchmarks" / "results"


def models_real_test12() -> str:
    """EXP-20260925-LM-1: models on 12 real datasets, declared paired comparisons with Holm."""
    import real_bench  # benchmarks/real_bench.py

    df = pd.read_csv(RESULTS / "engine-2026-09-25-models" / "test12" / "all_rows_real.csv")
    head = ["<!-- generated by paper/make_figures.py from "
            "benchmarks/results/engine-2026-09-25-models/test12/all_rows_real.csv; do not edit -->",
            "Source: EXP-20260925-LM-1 (exploratory).", ""]
    return "\n".join(head + real_bench.models_section(df)) + "\n"


# Caption templates hold no digits (tests/test_paper_tables.py); every number is read from a result file.
GEN = "<!-- generated by paper/make_figures.py from {src}; do not edit -->"
MOTIF_CAPTION = ("Table: paired difference (cisTarget motif prior minus the same model without it) in the "
                 "{metric} on the CollecTRI evaluation half, auto pipeline; unit = dataset, paired t, "
                 "Holm over the directed hypotheses of each run. Source: {exps}. {status}")
SELECTION_CAPTION = ("Table: reference-free selection against the fixed baseline pipeline and, with the "
                     "reference, gene-set-preserving screening against the baseline; AUPRC ratio on the "
                     "CollecTRI evaluation half, unit = dataset, paired t, Holm over the directed "
                     "hypotheses of each condition. Source: {exp}. Confirmatory for the clean condition (primary); "
                     "the other conditions are pre-registered secondary conditions.")
CLEANING_CAPTION = ("Table: mean change in AUPRC ratio of each single cleaning change against the fixed "
                    "baseline, on the variant's own gene universe and on the genes shared with the "
                    "baseline; unit = dataset. Source: {exp}. Exploratory, descriptive means only, no "
                    "p-values, no claim.")

MOTIF_RUNS = [  # (claim, experiment, model families the run is declared to compare)
    ("C4", "EXP-20260925-LM-2"), ("C5", "EXP-20260926-LM-1"), ("C6", "EXP-20261002-LM-1")]
MOTIF_ONLY = {"C4": {"pearson"}, "C5": {"regdiffusion", "grnboost2"}, "C6": {"pearson", "regdiffusion", "grnboost2"}}
SELECTION_EXP = "EXP-20261003-LM-1"
CLEANING_EXP = "EXP-20261004-LM-1"


def _md(head: list[str], rows: list[list]) -> list[str]:
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] +            ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def _interval(ci) -> str:
    return "unbounded" if ci is None or ci[0] is None else f"[{ci[0]:+.3f}, {ci[1]:+.3f}]"


def motif_lift_records(metric: str, arm: str = "auto") -> list[dict]:
    """Motif-prior pairs of C4-C6 through the report's own code path (texreport.comparisons)."""
    from grnbench import texreport

    recs = []
    for claim, exp in MOTIF_RUNS:
        df = texreport.load_rows(RESULTS / exp)
        for r in texreport.comparisons(df, metric, arm):
            fam = r["a"].removesuffix("_motif")
            if r["a"].endswith("_motif") and fam in MOTIF_ONLY[claim] and r["b"].removesuffix("_signed") == fam:
                recs.append({"claim": claim, "exp": exp, "metric": metric, "arm": arm, **r})
    return recs


MOTIF_STATUS = {"auprc_ratio": "Confirmatory: the pre-registered primary endpoint of every run.",
                "epr": "Pre-registered secondary endpoint of every run, not used for its hypotheses."}


def _motif_table(metric: str, label: str) -> str:
    recs = motif_lift_records(metric)
    exps = ", ".join(e for _, e in MOTIF_RUNS)
    src = ", ".join(f"benchmarks/results/{e}/rows" for _, e in MOTIF_RUNS)
    head = ["claim", "experiment", "A", "B", "n", "mean A-B", "95% interval", "p(A>B) Holm",
            "Holm family size", "metric", "arm"]
    rows = [[r["claim"], r["exp"], r["a"], r["b"], r["n"], f"{r['diff']:+.3f}", _interval(r["ci"]),
             f"{r['p_a_gt_b']:.3g}", r["family"], label, r["arm"]] for r in recs]
    caption = MOTIF_CAPTION.format(metric=label, exps=exps, status=MOTIF_STATUS[metric])
    return "\n".join([GEN.format(src=src), caption, ""] + _md(head, rows)) + "\n"


def motif_lift_auprc() -> str:
    return _motif_table("auprc_ratio", "AUPRC ratio")


def motif_lift_epr() -> str:
    return _motif_table("epr", "EPR")


def selection_reference_free() -> str:
    """EXP-20261003-LM-1: CONFIRM_FAMILY rows exactly as written to CONFIRM.json (not recomputed)."""
    import json

    path = RESULTS / SELECTION_EXP / "CONFIRM.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    head = ["condition", "A", "B", "n", "excluded", "mean A-B", "95% interval", "p(A>B) Holm",
            "p(B>A) Holm", "supported"]
    rows = [[cond, r["a"], r["b"], r["n"], r["excluded"], f"{r['diff']:+.3f}", _interval(r["ci"]),
             f"{r['p_a_gt_b']:.3g}", f"{r['p_b_gt_a']:.3g}", r["supported"]]
            for cond, recs in data.items() for r in recs]
    return "\n".join([GEN.format(src=f"benchmarks/results/{SELECTION_EXP}/CONFIRM.json"),
                       SELECTION_CAPTION.format(exp=SELECTION_EXP), ""] + _md(head, rows)) + "\n"


def cleaning_variants_rows() -> list[list]:
    import json

    import candidate_study  # benchmarks/candidate_study.py

    rows = [json.loads(p.read_text(encoding="utf-8"))
            for p in sorted((RESULTS / CLEANING_EXP / "rows").glob("*.json"))]
    names = sorted({c["name"] for r in rows for c in r.get("candidates", []) if c["source"] == "variant"})
    out = []
    for cond in [c for c in candidate_study.CONDITIONS if any(r["condition"] == c for r in rows)]:
        ok = [r for r in rows if r["condition"] == cond and not r.get("error") and not r.get("skipped")]
        for name in names:
            own, shared = candidate_study.variant_deltas(ok, name)
            out.append([cond, name, len(own), f"{np.mean(own):+.3f}" if own else "-",
                        len(shared), f"{np.mean(shared):+.3f}" if shared else "-"])
    return out


def cleaning_variants() -> str:
    head = ["condition", "variant", "n own", "mean diff own genes", "n shared", "mean diff shared genes"]
    return "\n".join([GEN.format(src=f"benchmarks/results/{CLEANING_EXP}/rows"),
                       CLEANING_CAPTION.format(exp=CLEANING_EXP), ""]
                      + _md(head, cleaning_variants_rows())) + "\n"


OUTPUTS = {  # path under paper/ -> function returning text (tables) or writing a file (figures)
    "tables/T_models_real_EXP-20260925-LM-1.md": models_real_test12,
    "tables/T_motif_lift_real.md": motif_lift_auprc,
    "tables/T_motif_lift_real_epr.md": motif_lift_epr,
    "tables/T_selection_reference_free.md": selection_reference_free,
    "tables/T_cleaning_variants.md": cleaning_variants,
}


def main() -> int:
    for rel, fn in OUTPUTS.items():
        out = Path(__file__).parent / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        text = fn()
        if isinstance(text, str):
            out.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote paper/{rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
